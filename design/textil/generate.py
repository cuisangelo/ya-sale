def rects(grid):
    out = []
    for y, row in enumerate(grid):
        x = 0
        while x < len(row):
            if row[x] == "#":
                start = x
                while x < len(row) and row[x] == "#":
                    x += 1
                out.append(f'<rect x="{start}" y="{y}" width="{x - start}" height="1"/>')
            else:
                x += 1
    return "".join(out)


def svg(grid, fill, size=None, label=None):
    w, h = len(grid[0]), len(grid)
    dims = f' width="{size * w // max(w, h)}" height="{size * h // max(w, h)}"' if size else ""
    a11y = f' role="img" aria-label="{label}"' if label else ' aria-hidden="true"'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}"{dims}{a11y} '
            f'shape-rendering="crispEdges" fill="{fill}">{rects(grid)}</svg>')


def band_svg():
    """A woven border tile: cochinilla ground, qolle mini diamonds, anil edges."""
    tile = [
        "################",
        "................",
        "...#.......#....",
        "..###.....###...",
        ".#####...#####..",
        "..###.....###...",
        "...#.......#....",
        "................",
        "################",
    ]
    w, h = len(tile[0]), len(tile)
    edges = "".join(f'<rect x="0" y="{y}" width="{w}" height="1" fill="{COLORS["anil"]}"/>' for y in (0, h - 1))
    inner = [row if i not in (0, h - 1) else "." * w for i, row in enumerate(tile)]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" aria-hidden="true" '
            f'shape-rendering="crispEdges"><rect width="{w}" height="{h}" fill="{COLORS["cochinilla"]}"/>'
            f'{edges}<g fill="{COLORS["qolle"]}">{rects(inner)}</g></svg>')


def main(asset_dir: Path):
    asset_dir.mkdir(parents=True, exist_ok=True)
    for name, grid in MOTIFS.items():
        (asset_dir / f"motivo-{name}.svg").write_text(svg(grid, COLORS["cochinilla"]) + "\n")
    for name, grid in MODES.items():
        (asset_dir / f"modo-{name}.svg").write_text(svg(grid, COLORS[MODE_FAMILY[name]]) + "\n")
    (asset_dir / "franja.svg").write_text(band_svg() + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
